-- Remove the seven placeholder subjects (computer-science, ai, data-structures,
-- software-engineering, operating-systems, web-development, cyber-security).
-- They were stand-ins shared by every student and belong to no real course.
-- Their classrooms, doubts and answers cascade away with them.
--
-- Anything not attached to a course is by definition a leftover, so this is
-- written as "keep only what a course references" rather than a hardcoded list.
DELETE FROM public.doubts
WHERE classroom_id IN (
  SELECT c.id FROM public.classrooms c
  WHERE c.subject_slug NOT IN (SELECT subject_slug FROM public.course_subjects)
);
DELETE FROM public.subjects
WHERE slug NOT IN (SELECT subject_slug FROM public.course_subjects);

-- Give every real subject its classrooms, same 3-per-subject baseline.
INSERT INTO public.classrooms (subject_slug, room_number, capacity, status)
SELECT s.slug, n, 30, 'open'
FROM public.subjects s
CROSS JOIN generate_series(1, 3) AS n
ON CONFLICT (subject_slug, room_number) DO NOTHING;

-- Subjects for one year of a course: both semesters of that year, tagged so the
-- UI can group them. Year 1 -> semesters 1 and 2, year 2 -> 3 and 4, etc.
CREATE OR REPLACE FUNCTION public.get_course_subjects(_course_slug text, _year int)
RETURNS TABLE (slug text, name text, semester int, sort_order int)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT s.slug, s.name, cs.semester, cs.sort_order
  FROM public.course_subjects cs
  JOIN public.subjects s ON s.slug = cs.subject_slug
  WHERE cs.course_slug = _course_slug
    AND cs.semester IN (_year * 2 - 1, _year * 2)
  ORDER BY cs.semester, cs.sort_order, s.name;
$$;

REVOKE ALL ON FUNCTION public.get_course_subjects(text, int) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_course_subjects(text, int) TO authenticated;
