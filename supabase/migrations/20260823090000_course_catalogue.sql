-- Replace the seven placeholder subjects with the real course catalogue.
--
-- Kaenyon previously shipped seven generic CS topics that were the same for
-- everybody. Students actually study a fixed set of subjects per semester of a
-- named course, so a Civil second-year and a CSE second-year share almost
-- nothing. Onboarding now asks for degree, course and year, and the app shows
-- exactly the subjects for that year's two semesters.
--
-- Year -> semesters is (year * 2 - 1, year * 2): 1st year = sems 1 and 2,
-- 2nd = 3 and 4, and so on.
--
-- Parsed from "Subject list.docx": 24 courses (8 B.Tech, 16 B.Sc),
-- 572 distinct subjects, 946 course-semester-subject rows.

CREATE TABLE IF NOT EXISTS public.courses (
  slug        text PRIMARY KEY,
  name        text NOT NULL,
  degree      text NOT NULL CHECK (degree IN ('B.Tech', 'B.Sc')),
  duration_years int NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT ON public.courses TO anon, authenticated;
GRANT ALL ON public.courses TO service_role;
ALTER TABLE public.courses ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "courses public read" ON public.courses;
CREATE POLICY "courses public read" ON public.courses FOR SELECT USING (true);

-- Which subjects belong to which semester of which course.
CREATE TABLE IF NOT EXISTS public.course_subjects (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  course_slug  text NOT NULL REFERENCES public.courses(slug) ON DELETE CASCADE,
  semester     int  NOT NULL CHECK (semester BETWEEN 1 AND 8),
  subject_slug text NOT NULL REFERENCES public.subjects(slug) ON DELETE CASCADE,
  sort_order   int  NOT NULL DEFAULT 0,
  UNIQUE (course_slug, semester, subject_slug)
);
CREATE INDEX IF NOT EXISTS course_subjects_lookup
  ON public.course_subjects (course_slug, semester);
GRANT SELECT ON public.course_subjects TO anon, authenticated;
GRANT ALL ON public.course_subjects TO service_role;
ALTER TABLE public.course_subjects ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "course_subjects public read" ON public.course_subjects;
CREATE POLICY "course_subjects public read" ON public.course_subjects FOR SELECT USING (true);

-- Students pick a course, not a free-text string.
ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS degree      text,
  ADD COLUMN IF NOT EXISTS course_slug text REFERENCES public.courses(slug) ON DELETE SET NULL;


